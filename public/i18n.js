function localErrStr(s) {
  if (!s) return t("err.generic");
  // 稳定错误码优先命中（服务端 2026-09-18 起 error 字段统一为 E_XXX）：
  // 不受服务端中文文案改动影响。对象查表而非前缀判断 —— 便于将来收编非 E_ 前缀的码。
  if (typeof s === "string" && SERVER_ERR_CODES[s]) {
    return t(SERVER_ERR_CODES[s]);
  }
  if (SERVER_ERR_MAP[s]) return t(SERVER_ERR_MAP[s]);
  // 最长前缀匹配
  let bestKey = null, bestLen = 0;
  for (const k in SERVER_ERR_MAP) {
    if (s.indexOf(k) === 0 && k.length > bestLen) { bestKey = k; bestLen = k.length; }
  }
  if (bestKey) {
    const base = t(SERVER_ERR_MAP[bestKey]);
    const detail = cleanErrDetail(s.slice(bestLen));
    return detail ? base + "：" + detail : base;
  }
  // 兜底：未收录的**中文**原文绝不外泄（否则德语/英语界面会弹出中文）。
  // 仅对含中文字符的串替换为通用文案；英文码 / URL / 纯数字等原样返回，
  // 缩小回归面（这些本就该原样展示）。
  if (/[\u4e00-\u9fff]/.test(s)) return t("err.generic");
  return s;
}

// 清洗「最长前缀匹配」后追加的 detail：
// 后端错误串常为「前缀（含中文补充）」，如「中转鉴权失败（token 不匹配）」。
// 前缀本身已被翻译，但括号里的中文若不剔除，仍会泄漏到德语/英语界面。
// 规则：去掉中文字符及其包裹的括号，只保留有信息量的拉丁/数字细节。
function cleanErrDetail(detail) {
  if (!detail) return "";
  let d = detail.replace(/[（(][^）)]*[\u4e00-\u9fff][^）)]*[）)]/g, " "); // 含中文的括号段
  d = d.replace(/[\u4e00-\u9fff]+/g, " ");                              // 残余中文
  return d.replace(/\s+/g, " ").replace(/^[:：\s]+|[\s]+$/g, "").trim();
}

// 当前语言的 BCP-47 locale（用于 toLocaleString）
function localeOf() {
  return _lang === "zh" ? "zh-CN" : _lang === "de" ? "de-DE" : "en-US";
}

function detectLang() {
  try {
    const stored = localStorage.getItem(I18N_KEY);
    if (stored && I18N[stored]) return stored;
  } catch (e) {}
  const nav = (typeof navigator !== "undefined" && navigator.language ? navigator.language : "zh")
    .slice(0, 2).toLowerCase();
  if (I18N[nav]) return nav;
  return "zh";
}

function initLangSelect() {
  // 语言切换按钮组（中文 / EN / DE）：当前语言高亮，点击即切换
  const box = document.getElementById("langButtons");
  if (!box) return;
  // 首访：把检测到的语言写入记忆——否则点击检测语言时因与 _lang 相同
  // 不会触发 setLang，localStorage 一直为空，语言会随浏览器环境漂移
  try { if (!localStorage.getItem(I18N_KEY)) localStorage.setItem(I18N_KEY, _lang); } catch (e) {}
  const btns = box.querySelectorAll(".lang-btn");
  btns.forEach(function (b) {
    b.classList.toggle("active", b.dataset.lang === _lang);
    b.addEventListener("click", function () {
      if (b.dataset.lang !== _lang) setLang(b.dataset.lang);
    });
  });
}

