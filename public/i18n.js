// 给 URL 追加当前语言参数
function langUrl(url) {
  try {
    const u = new URL(url, typeof location !== "undefined" ? location.href : "https://x/");
    u.searchParams.set("lang", _lang);
    return u.href;
  } catch (e) { return url; }
}

// 落地读取 ?lang=xx：优先级 URL 参数 > 本站 localStorage > 浏览器语言。
// 命中后写入 localStorage（站内后续导航保持）并清掉 URL 参数保持地址干净。
function applyLangFromQuery() {
  if (typeof location === "undefined") return false;
  let hit = false;
  try {
    const q = new URLSearchParams(location.search);
    const l = q.get("lang");
    if (l && I18N[l]) {
      hit = true;
      if (l !== _lang) setLang(l);
      q.delete("lang");
      const rest = q.toString();
      history.replaceState(null, "", location.pathname + (rest ? "?" + rest : "") + location.hash);
    }
  } catch (e) {}
  return hit;
}
let _lang = "zh";
let _onLangChange = null;

function getLang() { return _lang; }

function setLang(lang) {
  if (!I18N[lang]) lang = "zh";
  _lang = lang;
  try { localStorage.setItem(I18N_KEY, lang); } catch (e) {}
  if (typeof document !== "undefined") {
    document.documentElement.setAttribute("lang", lang);
    applyI18n(document);
    // 网页标签跟随语言（切换语言后 <title> 同步为该语言标题）
    document.title = t("app.title");
    // 语言按钮组高亮跟随当前语言
    document.querySelectorAll("#langButtons .lang-btn").forEach(function (b) {
      b.classList.toggle("active", b.dataset.lang === lang);
    });
  }
  if (typeof _onLangChange === "function") _onLangChange(lang);
}

// 翻译：支持 {{param}} 占位；缺失键回退中文，再回退原键
function t(key, params) {
  const dict = I18N[_lang] || I18N.zh;
  let s = (key in dict) ? dict[key] : (key in I18N.zh ? I18N.zh[key] : key);
  if (params) {
    s = s.replace(/\{\{(\w+)\}\}/g, function (_, k) {
      return params[k] !== undefined ? params[k] : "";
    });
  }
  return s;
}

