if (typeof document !== "undefined") {
  _lang = detectLang();
  applyLangFromQuery();  // 跨站跳转带来的 ?lang= 优先于本地记忆
  document.documentElement.setAttribute("lang", _lang);
  applyI18n(document);
  document.title = t("app.title");  // 标签页标题随首载语言
  initLangSelect();

  // 跨站 <a> 点击时注入当前语言：捕获阶段先改写 href、不拦截导航，
  // 页面自有逻辑（如 FAB 收起态 preventDefault）不受影响；中键/新标签打开同样生效
  document.addEventListener("click", function (ev) {
    const a = ev.target && ev.target.closest ? ev.target.closest("a[href]") : null;
    if (!a) return;
    try {
      const u = new URL(a.href, location.href);
      if (u.host === location.host) return;               // 同站链接不管
      if (I18N_CROSS_LINKS.indexOf(u.host) === -1) return; // 只处理项目内跨站
      if (u.searchParams.get("lang") === _lang) return;    // 已是当前语言
      u.searchParams.set("lang", _lang);
      a.href = u.href;
    } catch (e) {}
  }, true);

  // 影响分析页的"返回查询"指向主站域名：
  // 线上环境总是改写；本地开发（localhost）保持相对路径，除非显式注入了 I18N_HOME_URL
  try {
    if (typeof window.I18N_HOME_URL !== "undefined" ||
        !/^(localhost|127\.0\.0\.1)$/.test(location.hostname)) {
      document.querySelectorAll('a.back-link[href="/"]').forEach(function (a) {
        a.setAttribute("href", I18N_HOME_URL);
      });
    }
  } catch (e) {}
}

